// MaxFeedbackRunes bounds teacher-written feedback, rather than its UTF-8 byte
// representation. A 2,000-character Russian comment remains valid.
// RU: Ограничение применяется к символам текста, а не к байтам UTF-8.
const MaxFeedbackRunes = 2000

var (
	// ErrInvalidFeedback means an empty or excessively long note.
	// RU: ErrInvalidFeedback — пустое или слишком длинное замечание.
	ErrInvalidFeedback = errors.New("invalid review feedback")
	// ErrStaleReview blocks a decision about an outdated or already-reviewed version.
	// RU: ErrStaleReview — попытка изменить статус неактуальной версии.
	ErrStaleReview = errors.New("version is not pending review")
)

// FeedbackKind distinguishes an ordinary comment from a return for revision.
// RU: FeedbackKind отделяет обычный комментарий от причины возврата.
type FeedbackKind string

const (
	FeedbackComment  FeedbackKind = "comment"
	FeedbackRevision FeedbackKind = "revision"
)

// Feedback is an immutable teacher note associated with a specific upload.
// Its timestamp is generated by the application clock, never by the browser.
// RU: Feedback — неизменяемое замечание к версии документа с системной датой.
type Feedback struct {
	ID            int64
	StudentID     int64
	RequirementID int64
	VersionID     int64
	Kind          FeedbackKind
	Text          string
	CreatedAt     time.Time
}

// initFeedback adds an append-only feedback table to existing local SQLite
// workspaces. It is idempotent and preserves previously uploaded documents.
// RU: Таблица добавляется без удаления старых данных и файлов.
func (s *Service) initFeedback(ctx context.Context) error {
	const schema = `CREATE TABLE IF NOT EXISTS review_feedback (
		id INTEGER PRIMARY KEY AUTOINCREMENT,
		student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
		requirement_id INTEGER NOT NULL REFERENCES requirements(id) ON DELETE RESTRICT,
		version_id INTEGER NOT NULL REFERENCES file_versions(id) ON DELETE RESTRICT,
		kind TEXT NOT NULL CHECK (kind IN ('comment','revision')),
		body TEXT NOT NULL CHECK (length(trim(body)) > 0),
		created_at TEXT NOT NULL
	)`
	if _, err := s.DB.ExecContext(ctx, schema); err != nil {
		return fmt.Errorf("initialize review feedback: %w", err)
	}
	if _, err := s.DB.ExecContext(ctx, "CREATE INDEX IF NOT EXISTS idx_review_feedback_scope ON review_feedback(student_id,requirement_id,id)"); err != nil {
		return fmt.Errorf("index review feedback: %w", err)
	}
	return nil
}

// cleanFeedback validates text before beginning a database transaction.
// RU: Валидация не допускает пустое замечание и слишком длинный текст.
func cleanFeedback(text string) (string, error) {
	text = strings.TrimSpace(text)
	if text == "" || utf8.RuneCountInString(text) > MaxFeedbackRunes || !utf8.ValidString(text) {
		return "", ErrInvalidFeedback
	}
	return text, nil
}

// insertFeedback writes one review note on an existing SQL transaction. The
// caller is responsible for verifying the version scope and committing.
// RU: Вставка в существующую транзакцию позволяет атомарно менять статус.
func (s *Service) insertFeedback(ctx context.Context, tx *sql.Tx, studentID, requirementID, versionID int64, kind FeedbackKind, text string) (Feedback, error) {
	stamp := s.Clock().UTC()
	result, err := tx.ExecContext(ctx, `INSERT INTO review_feedback
		(student_id,requirement_id,version_id,kind,body,created_at)
		VALUES(?,?,?,?,?,?)`, studentID, requirementID, versionID, string(kind), text, stamp.Format(time.RFC3339Nano))
	if err != nil {
		return Feedback{}, fmt.Errorf("save review feedback: %w", err)
	}
	id, err := result.LastInsertId()
	if err != nil {
		return Feedback{}, fmt.Errorf("get feedback ID: %w", err)
	}
	return Feedback{ID: id, StudentID: studentID, RequirementID: requirementID, VersionID: versionID, Kind: kind, Text: text, CreatedAt: stamp}, nil
}

// AddComment appends a note to a saved version without changing its workflow
// state. Historical versions remain available for commentary.
// RU: AddComment сохраняет замечание и не меняет статус документа.
func (s *Service) AddComment(ctx context.Context, studentID, requirementID, versionID int64, body string) (Feedback, error) {
	if err := ctx.Err(); err != nil { return Feedback{}, err }
	text, err := cleanFeedback(body)
	if err != nil { return Feedback{}, err }
	if _, err := s.versionInfo(ctx, studentID, requirementID, versionID); err != nil {
		return Feedback{}, err
	}
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil { return Feedback{}, fmt.Errorf("begin comment: %w", err) }
	defer tx.Rollback()
	note, err := s.insertFeedback(ctx, tx, studentID, requirementID, versionID, FeedbackComment, text)
	if err != nil { return Feedback{}, err }
	if err := tx.Commit(); err != nil { return Feedback{}, fmt.Errorf("commit comment: %w", err) }
	return note, nil
}

// RejectWithReason atomically records the rejection reason, material status
// and status history in one SQLite transaction. A decision is only permitted
// for the latest uploaded version while it is under review. The existing
// accepted-file projection is never deleted.
// RU: Возврат с причиной атомарен и не затрагивает ранее принятые файлы.
func (s *Service) RejectWithReason(ctx context.Context, studentID, requirementID, versionID int64, reason string) error {
	if err := ctx.Err(); err != nil { return err }
	text, err := cleanFeedback(reason)
	if err != nil { return err }
	if _, err := s.versionInfo(ctx, studentID, requirementID, versionID); err != nil { return err }
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil { return fmt.Errorf("begin rejection: %w", err) }
	defer tx.Rollback()

	var latestID int64
	if err := tx.QueryRowContext(ctx, `SELECT COALESCE(MAX(id),0) FROM file_versions
		WHERE student_id=? AND requirement_id=?`, studentID, requirementID).Scan(&latestID); err != nil {
		return fmt.Errorf("find latest version: %w", err)
	}
	var current materials.Status
	err = tx.QueryRowContext(ctx, `SELECT status FROM material_status
		WHERE student_id=? AND requirement_id=?`, studentID, requirementID).Scan(&current)
	if errors.Is(err, sql.ErrNoRows) { return ErrStaleReview }
	if err != nil { return fmt.Errorf("read pending status: %w", err) }
	if versionID != latestID || current != materials.UnderReview { return ErrStaleReview }

	now := s.Clock().UTC().Format(time.RFC3339Nano)
	if _, err := tx.ExecContext(ctx, `UPDATE material_status SET status=?,changed_at=?
		WHERE student_id=? AND requirement_id=?`, string(materials.NeedsRevision), now, studentID, requirementID); err != nil {
		return fmt.Errorf("set revision status: %w", err)
	}
	if _, err := tx.ExecContext(ctx, `INSERT INTO material_events
		(student_id,requirement_id,status,occurred_at) VALUES(?,?,?,?)`,
		studentID, requirementID, string(materials.NeedsRevision), now); err != nil {
		return fmt.Errorf("record revision event: %w", err)
	}
	if _, err := s.insertFeedback(ctx, tx, studentID, requirementID, versionID, FeedbackRevision, text); err != nil { return err }
	if err := tx.Commit(); err != nil { return fmt.Errorf("commit revision: %w", err) }
	return nil
}

// ListFeedback retrieves all version-specific notes of one scoped requirement,
// oldest first. It never mixes another student's comments into the response.
// RU: ListFeedback читает историю замечаний для одной ВКР и требования.
func (s *Service) ListFeedback(ctx context.Context, studentID, requirementID int64) ([]Feedback, error) {
	if err := ctx.Err(); err != nil { return nil, err }
	if studentID <= 0 || requirementID <= 0 { return nil, ErrInvalidVersion }
	rows, err := s.DB.QueryContext(ctx, `SELECT id,student_id,requirement_id,version_id,kind,body,created_at
		FROM review_feedback WHERE student_id=? AND requirement_id=? ORDER BY id`,
		studentID, requirementID)
	if err != nil { return nil, fmt.Errorf("list feedback: %w", err) }
	defer rows.Close()
	result := make([]Feedback,0)
	for rows.Next() {
		var item Feedback
		var at string
		if err := rows.Scan(&item.ID,&item.StudentID,&item.RequirementID,&item.VersionID,&item.Kind,&item.Text,&at); err != nil {
			return nil, fmt.Errorf("scan feedback: %w",err)
		}
		item.CreatedAt,err = time.Parse(time.RFC3339Nano,at)
		if err != nil { return nil, fmt.Errorf("parse feedback timestamp: %w",err) }
		result=append(result,item)
	}
	if err := rows.Err(); err != nil { return nil, fmt.Errorf("read feedback rows: %w",err) }
	return result,nil
}
